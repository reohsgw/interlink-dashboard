"""Turn interlink_data.json (output of build_interlink.py) into data/data.js for the web page.
Usage: python scripts/make_web_data.py path/to/interlink_data.json
"""
import json, sys, os
src = sys.argv[1] if len(sys.argv) > 1 else 'interlink_data.json'
d = json.load(open(src, encoding='utf-8'))
s = json.dumps(d, ensure_ascii=False, separators=(',', ':'))
out = os.path.join(os.path.dirname(__file__), '..', 'data')
open(os.path.join(out, 'interlink_data.json'), 'w', encoding='utf-8').write(s)
open(os.path.join(out, 'data.js'), 'w', encoding='utf-8').write('// Generated by scripts/make_web_data.py. Do not edit by hand.\nconst DATA = ' + s + ';\n')
print('wrote data/data.js and data/interlink_data.json')
